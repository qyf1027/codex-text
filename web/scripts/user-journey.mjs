import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { createServer } from 'vite';

const server = await createServer({ server: { host: '127.0.0.1', port: 0 } });
await server.listen();
const base = `http://127.0.0.1:${server.httpServer.address().port}/`;
const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}), args: ['--no-sandbox'] });
const page = await browser.newPage({ acceptDownloads: true });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const check = async label => { assert.deepEqual(errors, [], `${label}: page errors`); assert.equal(await page.getByRole('alert').count(), 0, `${label}: UI error ${await page.getByRole('alert').allInnerTexts()}`); console.log(`OK ${label}`); };
try {
  await page.goto(base);
  await page.getByText('已保存到此浏览器').waitFor();
  await check('first load');
  await page.getByRole('button', { name: '数据管理' }).click();
  await page.getByRole('textbox', { name: '新项目名称' }).fill('真实操作验收');
  await page.getByRole('button', { name: '新建', exact: true }).click();
  await check('create project');
  await page.getByRole('button', { name: '任务与成果' }).click();
  await page.getByRole('textbox', { name: '新增阶段' }).fill('TR1 规划');
  await page.getByRole('button', { name: '添加阶段' }).click();
  await page.getByRole('textbox', { name: '新任务' }).fill('需求分析');
  await page.getByRole('button', { name: '添加', exact: true }).click();
  await page.getByRole('combobox', { name: '所属任务' }).selectOption({ label: '需求分析' });
  await page.getByRole('textbox', { name: '新成果' }).fill('需求规格书');
  await page.getByRole('button', { name: '添加成果' }).click();
  await check('stage task outcome');
  await page.getByRole('combobox', { name: '阶段', exact: true }).selectOption({ label: 'TR1 规划' });
  await page.getByRole('button', { name: '数据管理' }).click();
  await page.getByRole('textbox', { name: '新项目名称' }).fill('切换项目 B');
  await page.getByRole('button', { name: '新建', exact: true }).click();
  await page.getByRole('button', { name: '任务与成果' }).click();
  await page.getByRole('textbox', { name: '新任务' }).fill('B 的任务');
  await page.getByRole('button', { name: '添加', exact: true }).click();
  await check('task creation after switching project');
  await page.getByRole('combobox', { name: '切换项目' }).selectOption({ label: '真实操作验收' });
  await page.getByRole('button', { name: '总览' }).click();
  await page.getByPlaceholder('例如 TR1 评审').fill('TR1 评审');
  await page.locator('form').filter({ has: page.getByPlaceholder('例如 TR1 评审') }).locator('input[type=date]').fill('2027-12-01');
  await page.getByRole('combobox', { name: '完成判据' }).selectOption({ label: '成果：需求规格书' });
  await page.getByRole('button', { name: '添加 GA' }).click();
  await check('gate and criterion');
  await page.getByPlaceholder('例如 TR1 评审').fill('早期 GA');
  await page.locator('form').filter({ has: page.getByPlaceholder('例如 TR1 评审') }).locator('input[type=date]').fill('2026-11-30');
  await page.getByRole('button', { name: '添加 GA' }).click();
  assert.match(await page.getByText('下一个 GA').locator('..').innerText(), /目标：2026-11-30/, 'overview must show nearest GA target');
  await page.getByRole('button', { name: '生成候选' }).last().click();
  await check('schedule candidate');
  assert.ok(await page.getByRole('heading', { name: '未采纳的排期候选' }).isVisible());
  await page.getByRole('textbox', { name: 'TR1 评审目标日期' }).fill('2027-12-02');
  assert.equal(await page.getByRole('heading', { name: '未采纳的排期候选' }).count(), 0, 'candidate must close when constraints change');
  await page.getByRole('button', { name: '关键资源' }).click();
  await page.getByRole('textbox', { name: '新资源名称' }).fill('样机');
  await page.getByRole('button', { name: '添加资源' }).click();
  await page.getByRole('combobox', { name: '预约资源' }).selectOption({ label: '样机' });
  await page.getByRole('combobox', { name: '预约任务' }).selectOption({ label: '真实操作验收 / 需求分析' });
  await page.getByRole('button', { name: '添加预约' }).click();
  await check('resource booking');
  await page.getByRole('button', { name: '数据管理' }).click();
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: '导出完整工作区' }).click()]);
  const backup = JSON.parse(await (await import('node:fs/promises')).readFile(await download.path(), 'utf8'));
  assert.ok(backup.workspace.projects.some(p => p.name === '真实操作验收'));
  await page.locator('label', { hasText: '导入完整工作区' }).locator('input[type=file]').setInputFiles({ name: 'broken.json', mimeType: 'application/json', buffer: Buffer.from('{bad') });
  assert.match(await page.getByRole('alert').innerText(), /JSON|导入/);
  assert.ok(await page.getByRole('combobox', { name: '切换项目' }).isVisible());
  console.log('OK damaged backup rejected without data loss');
  await page.locator('label', { hasText: '导入完整工作区' }).locator('input[type=file]').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
  await page.getByRole('button', { name: /确认替换/ }).click();
  await page.getByText('已保存到此浏览器').waitFor();
  await page.reload();
  await page.getByRole('combobox', { name: '切换项目' }).waitFor();
  assert.equal(await page.getByRole('combobox', { name: '切换项目' }).inputValue(), backup.workspace.currentProjectId);
  await check('backup restore and reload');
  const fresh = await browser.newPage({ acceptDownloads: true });
  await fresh.goto(base);
  await fresh.getByText('已保存到此浏览器').waitFor();
  await fresh.getByRole('button', { name: '数据管理' }).click();
  await fresh.locator('label', { hasText: '导入完整工作区' }).locator('input[type=file]').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
  await fresh.getByRole('button', { name: /确认替换/ }).click();
  await fresh.getByText('已保存到此浏览器').waitFor();
  await fresh.reload();
  await fresh.getByRole('combobox', { name: '切换项目' }).waitFor();
  assert.equal(await fresh.getByRole('combobox', { name: '切换项目' }).inputValue(), backup.workspace.currentProjectId);
  await fresh.getByRole('button', { name: '数据管理' }).click();
  const [projectDownload] = await Promise.all([fresh.waitForEvent('download'), fresh.getByRole('button', { name: '导出当前项目' }).click()]);
  const projectFile = await (await import('node:fs/promises')).readFile(await projectDownload.path());
  const before = await fresh.getByRole('combobox', { name: '切换项目' }).locator('option').count();
  await fresh.locator('label', { hasText: '导入为新项目' }).locator('input[type=file]').setInputFiles({ name: 'project.json', mimeType: 'application/json', buffer: projectFile });
  await fresh.getByRole('button', { name: '确认导入' }).click();
  assert.equal(await fresh.getByRole('combobox', { name: '切换项目' }).locator('option').count(), before + 1);
  console.log('OK single-project export and import');
  const legacy = { projectName: '旧版样例', projectStart: '2026-10-26', targetGA: '2027-01-01', tasks: [{ name: '需求梳理', phase: 'TR1', standardDuration: 3, limitDuration: 2 }] };
  await fresh.locator('label', { hasText: '导入旧版项目 JSON' }).locator('input[type=file]').setInputFiles({ name: 'legacy.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(legacy)) });
  await fresh.getByRole('button', { name: '确认转换' }).click();
  assert.equal(await fresh.getByRole('combobox', { name: '切换项目' }).locator('option').count(), before + 2);
  console.log('OK legacy import');
  await fresh.close();
  console.log('OK restore into fresh browser');
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await mobile.goto(base);
  await mobile.getByRole('button', { name: '任务与成果' }).click();
  const dimensions = await mobile.evaluate(() => ({ viewport: innerWidth, content: document.documentElement.scrollWidth }));
  assert.ok(dimensions.content <= dimensions.viewport + 5, `mobile horizontal overflow: ${JSON.stringify(dimensions)}`);
  await mobile.close();
  console.log('OK narrow viewport');
  const empty = await browser.newPage();
  await empty.goto(base);
  await empty.getByRole('button', { name: '数据管理' }).click();
  await empty.getByRole('button', { name: '删除当前项目' }).click();
  await empty.getByRole('button', { name: '确认删除' }).click();
  await empty.getByRole('heading', { name: '还没有项目' }).waitFor();
  await empty.locator('label', { hasText: '选择工作区备份' }).locator('input[type=file]').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{bad') });
  assert.ok(await empty.getByRole('alert').isVisible(), 'invalid restore on empty workspace must show the error');
  await empty.getByRole('textbox', { name: '新项目名称' }).fill('重新开始');
  await empty.getByRole('button', { name: '新建项目' }).click();
  await empty.getByRole('combobox', { name: '切换项目' }).waitFor();
  assert.ok((await empty.getByRole('combobox', { name: '切换项目' }).innerText()).includes('重新开始'));
  await empty.close();
  console.log('OK delete last project and restart');
  console.log('user-journey: pass');
} finally { await browser.close(); await server.close(); }
