import { chromium } from 'playwright';
import { createServer } from 'vite';
import { resolve } from 'node:path';
const server = await createServer({ server: { host: '127.0.0.1', port: 0 } });
await server.listen();
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1200 } });
const shot = name => page.screenshot({ path: resolve('../docs/manual-assets', `${name}.png`), animations: 'disabled' });
try {
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/`);
  await page.getByText('已保存到此浏览器').waitFor();
  await shot('01-overview');
  await page.getByRole('button', { name: '任务与成果' }).click();
  await shot('02-tasks');
  await page.getByRole('button', { name: '数据管理' }).click();
  await page.getByRole('textbox', { name: '新项目名称' }).fill('产品 A');
  await page.getByRole('button', { name: '新建', exact: true }).click();
  await page.getByRole('button', { name: '任务与成果' }).click();
  await page.getByRole('textbox', { name: '新任务' }).fill('需求分析');
  await page.getByRole('button', { name: '添加', exact: true }).click();
  await page.getByRole('combobox', { name: '所属任务' }).selectOption({ label: '需求分析' });
  await page.getByRole('textbox', { name: '新成果' }).fill('需求规格书');
  await page.getByRole('button', { name: '添加成果' }).click();
  await shot('03-outcome');
  await page.getByRole('button', { name: '总览' }).click();
  await page.getByPlaceholder('例如 TR1 评审').fill('TR1 评审');
  await page.getByRole('combobox', { name: '完成判据' }).selectOption({ label: '成果：需求规格书' });
  await page.getByRole('button', { name: '添加 GA' }).click();
  await shot('04-gate');
  await page.getByRole('button', { name: '数据管理' }).click();
  await page.getByRole('textbox', { name: '新项目名称' }).fill('产品 B');
  await page.getByRole('button', { name: '新建', exact: true }).click();
  await page.getByRole('button', { name: '任务与成果' }).click();
  await page.getByRole('textbox', { name: '新任务' }).fill('样机测试');
  await page.getByRole('button', { name: '添加', exact: true }).click();
  await page.getByRole('button', { name: '跨项目依赖' }).click();
  await page.getByRole('combobox', { name: '前置成果' }).selectOption({ label: '产品 A / 需求规格书' });
  await page.getByRole('combobox', { name: '目标' }).selectOption({ label: '产品 B / 样机测试' });
  await page.getByRole('button', { name: '建立依赖' }).click();
  await shot('05-dependency');
  await page.getByRole('button', { name: '关键资源' }).click();
  await page.getByRole('textbox', { name: '新资源名称' }).fill('测试设备 1');
  await page.getByRole('button', { name: '添加资源' }).click();
  await page.getByRole('combobox', { name: '预约资源' }).selectOption({ label: '测试设备 1' });
  await page.getByRole('combobox', { name: '预约任务' }).selectOption({ label: '产品 B / 样机测试' });
  await page.getByRole('button', { name: '添加预约' }).click();
  await shot('06-resources');
  await page.getByRole('button', { name: '数据管理' }).click();
  await shot('07-backup');
  console.log('captured 7 actual app screens');
} finally { await browser.close(); await server.close(); }
